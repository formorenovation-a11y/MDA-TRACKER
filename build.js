#!/usr/bin/env node
/**
 * build.js — regenerates server.js from index.html.
 *
 * index.html is the single source of truth for the app.
 * server.js serves it from disk when the file is present, and falls back to
 * an embedded copy (written by this script) when it is not.
 *
 * Run after any edit to index.html:
 *     node build.js
 */
const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const html = fs.readFileSync(path.join(ROOT, "index.html"), "utf8");

// Escape for embedding inside a JS template literal.
const embedded = html
  .replace(/\\/g, "\\\\")
  .replace(/`/g, "\\`")
  .replace(/\$\{/g, "\\${");

const server = `const http = require("http");
const https = require("https");
const fs = require("fs");
const path = require("path");

const PORT = process.env.PORT || 3000;
const ANTHROPIC_KEY = process.env.ANTHROPIC_API_KEY || "";

// ── Fallback copy of index.html ──────────────────────────────────────────
// GENERATED BY build.js — do not edit by hand. Edit index.html and re-run:
//     node build.js
const HTML_FALLBACK = \`${embedded}\`;

// Prefer the file on disk so a deploy that ships index.html always serves the
// latest markup, even if this fallback is stale.
function loadHTML(){
  try {
    const p = path.join(__dirname, "index.html");
    if (fs.existsSync(p)) return fs.readFileSync(p, "utf8");
  } catch (e) {
    console.warn("index.html unreadable, using embedded fallback:", e.message);
  }
  return HTML_FALLBACK;
}
let HTML = loadHTML();

// ── Anthropic proxy — keeps the API key server-side ──────────────────────
function proxyAnthropic(body, res) {
  const payload = JSON.stringify(body);
  const options = {
    hostname: "api.anthropic.com",
    path: "/v1/messages",
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "Content-Length": Buffer.byteLength(payload),
      "x-api-key": ANTHROPIC_KEY,
      "anthropic-version": "2023-06-01",
      "anthropic-beta": "pdfs-2024-09-25"
    }
  };
  const req = https.request(options, (apiRes) => {
    let data = "";
    apiRes.on("data", chunk => data += chunk);
    apiRes.on("end", () => {
      res.writeHead(apiRes.statusCode, { "Content-Type": "application/json", "Access-Control-Allow-Origin": "*" });
      res.end(data);
    });
  });
  req.on("error", err => {
    res.writeHead(500, { "Content-Type": "application/json" });
    res.end(JSON.stringify({ error: err.message }));
  });
  req.write(payload);
  req.end();
}

const server = http.createServer((req, res) => {
  if (req.method === "OPTIONS") {
    res.writeHead(204, {
      "Access-Control-Allow-Origin": "*",
      "Access-Control-Allow-Methods": "POST",
      "Access-Control-Allow-Headers": "Content-Type"
    });
    res.end();
    return;
  }

  if (req.method === "GET" && (req.url === "/" || req.url === "/index.html")) {
    res.writeHead(200, { "Content-Type": "text/html; charset=utf-8", "Cache-Control": "no-cache" });
    res.end(HTML);
    return;
  }

  if (req.method === "GET" && req.url === "/healthz") {
    res.writeHead(200, { "Content-Type": "application/json" });
    res.end(JSON.stringify({ ok: true, bytes: HTML.length, key: Boolean(ANTHROPIC_KEY) }));
    return;
  }

  if (req.method === "POST" && req.url === "/api/analyze") {
    if (!ANTHROPIC_KEY) {
      res.writeHead(500, { "Content-Type": "application/json" });
      res.end(JSON.stringify({ error: "ANTHROPIC_API_KEY not set in Render environment" }));
      return;
    }
    let body = "";
    req.on("data", chunk => {
      body += chunk;
      if (body.length > 40 * 1024 * 1024) { req.destroy(); }
    });
    req.on("end", () => {
      try { proxyAnthropic(JSON.parse(body), res); }
      catch (e) {
        res.writeHead(400, { "Content-Type": "application/json" });
        res.end(JSON.stringify({ error: "Invalid JSON" }));
      }
    });
    return;
  }

  res.writeHead(404, { "Content-Type": "text/plain" });
  res.end("Not found");
});

server.listen(PORT, () => console.log("MDA Tracker running on port " + PORT));
`;

fs.writeFileSync(path.join(ROOT, "server.js"), server, "utf8");
console.log(`server.js regenerated — ${(server.length / 1024).toFixed(0)} KB (index.html: ${(html.length / 1024).toFixed(0)} KB)`);
